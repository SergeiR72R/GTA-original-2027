// Собирает CLAUDE_CHROME_ASSETS.md и PROMPTS.md из js/asset-manifest.js,
// чтобы номера и промпты в инструкциях совпадали с импортёром.
// Запуск: node tools/build-asset-docs.js
'use strict';

const fs = require('fs');
const path = require('path');
const { ASSET_MANIFEST } = require('../js/asset-manifest.js');

const root = path.join(__dirname, '..');
const CAT = { vehicles: 'Машины', chars: 'Персонажи', facades: 'Фасады и витрины', props: 'Объекты улиц', textures: 'Текстуры' };
const total = ASSET_MANIFEST.length;
const count = (c) => ASSET_MANIFEST.filter((a) => a.cat === c).length;

function assetList(forAgent) {
  let out = '';
  let cat = null;
  for (const [i, a] of ASSET_MANIFEST.entries()) {
    if (a.cat !== cat) {
      cat = a.cat;
      out += `\n## ${CAT[cat]} (${count(cat)})\n\n`;
      if (forAgent && cat === 'vehicles') out += 'Каждую машину делай в **новом чате**: сначала базовая картинка, затем три правки той же картинки (`_d1`, `_d2`, `_d3`) в этом же чате.\n\n';
      if (forAgent && cat === 'chars') out += 'Все персонажи — в одном чате (если чат стал медленным, начни новый и продолжай с того же номера).\n\n';
      if (forAgent && cat === 'props') out += 'Все объекты — в одном новом чате.\n\n';
      if (forAgent && cat === 'facades') out += 'Все фасады и витрины — в одном новом чате, **формат 16:9**, вид строго спереди (как чертёж), без неба и перспективы.\n\n';
      if (forAgent && cat === 'textures') out += 'Все текстуры — в одном новом чате.\n\n';
    }
    const n = i + 1;
    const head = `### ${n}. \`${a.cat}/${a.file}.png\` — ${a.title}`;
    const kind = a.kind === 'edit'
      ? `Правка картинки \`${a.base}\` из этого же чата.`
      : `Новая картинка, формат ${a.size === '768x1024' ? 'вертикальный 3:4' : a.size === '16:9' ? 'горизонтальный 16:9' : 'квадрат 1:1'}.`;
    out += `${head}\n\n${forAgent ? '- [ ] ' : ''}${kind}\n\n\`\`\`\n${a.prompt}\n\`\`\`\n\n`;
  }
  return out;
}

