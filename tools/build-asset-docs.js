const FLOW_SIZE = { '768x1024': 'портрет 3:4 (если нет — 9:16)', '1024x1024': 'квадрат 1:1', '16:9': 'пейзаж 16:9' };
const ALL = ASSET_MANIFEST.map((a, i) => Object.assign({ n: i + 1 }, a));

function flowList(list) {
  let out = '', cat = null;
  for (const a of list) {
    const c = a.cat === 'facades' && a.file.startsWith('poster') ? 'posters' : a.cat;
    if (c !== cat) {
      cat = c;
      const title = c === 'posters' ? 'Иллюстрации для рекламных щитов' : CAT[c];
      out += `\n## ${title} (${list.filter((x) => (x.cat === 'facades' && x.file.startsWith('poster') ? 'posters' : x.cat) === c).length})\n\n`;
    }
    const full = a.full || (a.kind === 'edit' ? ALL.find((b) => b.file === a.base).prompt + ' ' + a.prompt.replace(/^Edit the previous image of this exact vehicle\. Keep EXACTLY the same [^.]*\. /, '') : null);
    const how = a.kind === 'edit'
      ? `Правка картинки \`${a.base}\`: если в Flow можно редактировать картинку или взять её как образец, используй короткий промпт «Правка» (возьми за образец уже готовую \`${a.base}\`). Если нельзя — генерируй по полному промпту. Формат ${FLOW_SIZE[a.size]}.`
      : `Новая картинка, формат ${FLOW_SIZE[a.size]}.`;
    out += `### ${a.n}. \`${a.cat}/${a.file}.png\` — ${a.title}\n\n- [ ] ${how}\n\n`;
    if (a.kind === 'edit') out += `Правка:\n\n\`\`\`\n${a.prompt}\n\`\`\`\n\nПолный промпт:\n\n\`\`\`\n${full}\n\`\`\`\n\n`;
    else out += `\`\`\`\n${a.prompt}\n\`\`\`\n\n`;
  }
  return out;
}

